    private static GameMeta g(String id, String name, String cat, String brief,
                              String tutorial, Class<?> impl) {
        return new GameMeta(id, name, cat, brief, tutorial, impl);
    }

    public static final int TOTAL = ALL.length;

    public static GameMeta get(String id) {
        for (GameMeta m : ALL) if (m.id.equals(id)) return m;
        return null;
    }

    /** 游戏在注册表中的序号（0..99），用于给每款游戏分配独立配色/图标。 */
    public static int indexOf(String id) {
        for (int i = 0; i < ALL.length; i++) if (ALL[i].id.equals(id)) return i;
        return -1;
    }

    @SuppressWarnings("unchecked")
    public static Game create(String id) {
        GameMeta m = get(id);
        if (m == null || !m.playable()) return null;
        try {
            return ((Class<? extends Game>) m.impl).newInstance();
        } catch (Exception e) {
            return null;
        }
    }

